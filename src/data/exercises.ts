const T = (name: string, list: [string, number, number, number?][]): Template => ({
  id: 't-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
  name,
  exercises: list.map(([n, sets, reps, rest]) => ({ exerciseId: id(n), sets, reps, restSec: rest ?? 120 })),
});

